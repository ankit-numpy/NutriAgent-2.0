        # Extract profile hints from the prompt
        is_veg = "Vegetarian" in prompt and "Non-Vegetarian" not in prompt
        has_diabetes = "diabetes" in prompt.lower()
        has_bp = "blood pressure" in prompt.lower() or "hypertension" in prompt.lower()

        diet_type = "Plant-based vegetarian" if is_veg else "Balanced omnivore"
