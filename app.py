import os
import json
import datetime
from dotenv import load_dotenv
from flask import Flask, render_template, request, jsonify, session, redirect, url_for
from agent import NutritionAgent

# Load .env before anything reads os.environ
load_dotenv()

app = Flask(__name__)
app.secret_key = os.environ.get("FLASK_SECRET_KEY", "nutribot2-secret-key-2026")

agent = NutritionAgent()


# ─────────────────────────────────────────────
# Routes
# ─────────────────────────────────────────────

@app.route("/")
def index():
    """Landing page — user intake form."""
    return render_template("index.html")


@app.route("/generate", methods=["POST"])
def generate():
    """Accept user profile form, generate nutrition plan."""
    data = request.form.to_dict(flat=True)

    # Basic server-side validation
    required = ["name", "age", "diet", "city", "country"]
    for field in required:
        if not data.get(field, "").strip():
            return render_template("index.html",
                                   error=f"Field '{field}' is required.")

    # Collect medical flags (checkboxes)
    medical_conditions = request.form.getlist("medical_history")
    data["medical_history"] = medical_conditions

    # Store profile in session for the Q&A chat
    session["user_profile"] = data

    # Run agentic plan generation
    result = agent.generate_plan(data)

    # Persist plan to markdown file
    md_path = _save_plan_to_md(data, result["plan"])

    return render_template(
        "result.html",
        profile=data,
        plan=result["plan"],
        plan_html=result["plan_html"],
        disclaimer=result["disclaimer"],
        md_filename=os.path.basename(md_path),
        llm_used=result.get("llm_used", False),
        llm_error=result.get("llm_error", ""),
    )


@app.route("/chat", methods=["POST"])
def chat():
    """Agentic Q&A endpoint — returns JSON."""
    payload = request.get_json(force=True)
    user_message = payload.get("message", "").strip()

    if not user_message:
        return jsonify({"error": "Empty message"}), 400

    profile = session.get("user_profile", {})
    response = agent.answer_query(user_message, profile)
    return jsonify({"reply": response})


@app.route("/download/<filename>")
def download_plan(filename):
    """Serve the saved markdown nutrition plan."""
    from flask import send_from_directory
    plans_dir = os.path.join(os.path.dirname(__file__), "plans")
    return send_from_directory(plans_dir, filename, as_attachment=True)


# ─────────────────────────────────────────────
# Helpers
# ─────────────────────────────────────────────

def _save_plan_to_md(profile: dict, plan: str) -> str:
    """Write the personalised nutrition plan to a timestamped .md file."""
    plans_dir = os.path.join(os.path.dirname(__file__), "plans")
    os.makedirs(plans_dir, exist_ok=True)

    timestamp = datetime.datetime.now().strftime("%Y%m%d_%H%M%S")
    safe_name = profile["name"].replace(" ", "_").lower()
    filename = f"plan_{safe_name}_{timestamp}.md"
    filepath = os.path.join(plans_dir, filename)

    medical = ", ".join(profile.get("medical_history", [])) or "None"
    content = f"""# NutriBot 2.0 — Personalised Nutrition Plan

**Generated:** {datetime.datetime.now().strftime("%B %d, %Y %H:%M")}

## User Profile
| Field | Value |
|---|---|
| Name | {profile.get("name", "")} |
| Age | {profile.get("age", "")} |
| Diet Preference | {profile.get("diet", "")} |
| Medical History | {medical} |
| Location | {profile.get("city", "")}, {profile.get("country", "")} |

---

## Personalised Nutrition Plan

{plan}

---

> **Medical Disclaimer:** This nutrition plan is generated by an AI system and is intended
> for informational purposes only. It does not constitute medical advice, diagnosis, or
> treatment. Always consult a qualified healthcare professional or registered dietitian
> before making significant dietary changes, especially if you have existing medical
> conditions. NutriBot 2.0 disclaims all liability for any health outcomes resulting from
> acting on this information without professional guidance.
"""

    with open(filepath, "w", encoding="utf-8") as f:
        f.write(content)

    return filepath


